"""Tests for daterange (task fixture t-002)."""

import pytest

from daterange import days_between


@pytest.mark.parametrize(
    "start,end,expected",
    [
        ("2026-01-01", "2026-01-01", 0),
        ("2026-01-01", "2026-01-02", 1),
        ("2026-01-01", "2026-01-31", 30),
        ("2026-01-15", "2026-02-15", 31),
        ("2026-01-31", "2026-03-01", 29),
        ("2025-12-31", "2026-01-01", 1),
        ("2024-02-28", "2024-03-01", 2),
        ("2024-02-28", "2024-02-29", 1),
        ("2023-02-28", "2023-03-01", 1),
        ("2026-06-01", "2026-09-01", 92),
        ("2026-01-01", "2027-01-01", 365),
        ("2023-01-01", "2024-01-01", 366),
        ("2026-08-21", "2026-12-24", 125),
    ],
)
def test_days_between(start, end, expected):
    assert days_between(start, end) == expected
